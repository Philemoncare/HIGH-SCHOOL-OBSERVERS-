// Advanced helper functions for filtering and searching schools
export const filterSchoolsByRegion = (region) => {
  return ghanaSchools.filter(school => school.region === region);
};

export const filterSchoolsByType = (type) => {
  return ghanaSchools.filter(school => school.type === type);
};

export const filterSchoolsByCategory = (category) => {
  return ghanaSchools.filter(school => school.category === category);
};

export const filterSchoolsByProgram = (program) => {
  return ghanaSchools.filter(school => school.programs.includes(program));
};

export const filterSchoolsByFacility = (facility) => {
  return ghanaSchools.filter(school => school.facilities.includes(facility));
};

export const searchSchoolsByName = (searchTerm) => {
  const term = searchTerm.toLowerCase();
  return ghanaSchools.filter(school => 
    school.name.toLowerCase().includes(term) ||
    school.region.toLowerCase().includes(term) ||
    school.district.toLowerCase().includes(term)
  );
};

export const searchSchoolsAdvanced = (criteria) => {
  let results = ghanaSchools;
  
  if (criteria.region) {
    results = results.filter(school => school.region === criteria.region);
  }
  
  if (criteria.type) {
    results = results.filter(school => school.type === criteria.type);
  }
  
  if (criteria.category) {
    results = results.filter(school => school.category === criteria.category);
  }
  
  if (criteria.program) {
    results = results.filter(school => school.programs.includes(criteria.program));
  }
  
  if (criteria.facility) {
    results = results.filter(school => school.facilities.includes(criteria.facility));
  }
  
  if (criteria.searchTerm) {
    const term = criteria.searchTerm.toLowerCase();
    results = results.filter(school => 
      school.name.toLowerCase().includes(term) ||
      school.region.toLowerCase().includes(term) ||
      school.district.toLowerCase().includes(term)
    );
  }
  
  return results;
};

export const getUniqueRegions = () => {
  return [...new Set(ghanaSchools.map(school => school.region))].sort();
};

export const getUniqueTypes = () => {
  return [...new Set(ghanaSchools.map(school => school.type))].sort();
};

export const getUniqueCategories = () => {
  return [...new Set(ghanaSchools.map(school => school.category))].sort();
};

export const getUniquePrograms = () => {
  const allPrograms = ghanaSchools.flatMap(school => school.programs);
  return [...new Set(allPrograms)].sort();
};

export const getUniqueFacilities = () => {
  const allFacilities = ghanaSchools.flatMap(school => school.facilities);
  return [...new Set(allFacilities)].sort();
};

export const getSchoolStatistics = () => {
  const stats = {
    total: ghanaSchools.length,
    byRegion: {},
    byType: {},
    byCategory: {},
    averageEnrollment: 0,
    oldestSchool: null,
    newestSchool: null
  };
  
  // Calculate statistics
  ghanaSchools.forEach(school => {
    // By region
    stats.byRegion[school.region] = (stats.byRegion[school.region] || 0) + 1;
    
    // By type
    stats.byType[school.type] = (stats.byType[school.type] || 0) + 1;
    
    // By category
    stats.byCategory[school.category] = (stats.byCategory[school.category] || 0) + 1;
  });
  
  // Average enrollment
  const totalEnrollment = ghanaSchools.reduce((sum, school) => sum + school.enrollment, 0);
  stats.averageEnrollment = Math.round(totalEnrollment / ghanaSchools.length);
  
  // Oldest and newest schools
  const sortedByYear = [...ghanaSchools].sort((a, b) => a.established - b.established);
  stats.oldestSchool = sortedByYear[0];
  stats.newestSchool = sortedByYear[sortedByYear.length - 1];
  
  return stats;
}; 